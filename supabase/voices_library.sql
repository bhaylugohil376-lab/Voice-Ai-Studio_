-- VoiceAI: shared voice library metadata
create table if not exists public.voices_library (
 id bigint generated by default as identity primary key, voice_id text not null,
 provider text not null default 'elevenlabs', name text not null, category text,
 description text, preview_url text, labels jsonb not null default '{}'::jsonb,
 available_for_tts boolean not null default true, created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(), constraint voices_library_provider_voice_unique unique(provider,voice_id)
);
create index if not exists voices_library_provider_idx on public.voices_library(provider);
create index if not exists voices_library_name_idx on public.voices_library(name);
alter table public.voices_library enable row level security;
revoke all on public.voices_library from public,anon,authenticated;
grant select on public.voices_library to anon,authenticated;
revoke insert,update,delete on public.voices_library from anon,authenticated;
grant all on public.voices_library to service_role;
create or replace function public.set_voices_library_updated_at() returns trigger language plpgsql set search_path=pg_catalog,public as $$ begin new.updated_at=now(); return new; end; $$;
drop trigger if exists voices_library_updated_at on public.voices_library;
create trigger voices_library_updated_at before update on public.voices_library for each row execute function public.set_voices_library_updated_at();
drop policy if exists "Voice library is publicly readable" on public.voices_library;
create policy "Voice library is publicly readable" on public.voices_library for select to anon,authenticated using(true);
