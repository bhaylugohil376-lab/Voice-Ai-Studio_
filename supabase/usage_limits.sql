-- VoiceAI: atomic usage limits
-- Free plan: 5 uses per action in a rolling 24-hour window.
create table if not exists public.usage_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  action text not null check (action ~ '^[a-z][a-z0-9_]{1,49}$'),
  created_at timestamptz not null default now()
);
create index if not exists usage_logs_user_action_created_idx on public.usage_logs (user_id, action, created_at desc);
alter table public.usage_logs enable row level security;
revoke all on public.usage_logs from anon, authenticated;
grant all on public.usage_logs to service_role;
create or replace function public.check_and_use_ai(p_user_id uuid,p_action text,p_limit integer default 5,p_window_hours integer default 24)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_used integer; v_remaining integer; v_since timestamptz;
begin
  if p_user_id is null or p_action is null or p_action !~ '^[a-z][a-z0-9_]{1,49}$' then raise exception 'Invalid user or action'; end if;
  if p_limit is null or p_window_hours is null or p_limit < 1 or p_window_hours < 1 then raise exception 'Invalid usage limits'; end if;
  v_since := now() - make_interval(hours => p_window_hours);
  perform pg_advisory_xact_lock(hashtextextended(p_user_id::text || ':' || p_action,0));
  select count(*)::integer into v_used from public.usage_logs where user_id=p_user_id and action=p_action and created_at>=v_since;
  if v_used >= p_limit then return jsonb_build_object('allowed',false,'used',v_used,'remaining',0); end if;
  insert into public.usage_logs (user_id,action) values (p_user_id,p_action);
  v_remaining := greatest(0,p_limit-v_used-1);
  return jsonb_build_object('allowed',true,'used',v_used+1,'remaining',v_remaining);
end; $$;
revoke all on function public.check_and_use_ai(uuid,text,integer,integer) from public,anon,authenticated;
grant execute on function public.check_and_use_ai(uuid,text,integer,integer) to service_role;
